class QAbstractConcatenable(CuteMixin, metaclass=MetaCute):
  """
  The cute side of Qt's QAbstractConcatenable: a plain Python object standing
  in front of one C++ QAbstractConcatenable.

  C++ hands a QAbstractConcatenable around as a copy, so every C++
  QAbstractConcatenable behind a cute one is Python's own: it is removed, by
  the ritual named in '__delete_ritual__', when the cute object goes.

  What exists
  -----------

  Every function of Qt's QAbstractConcatenable that has a ritual and that
  Python can call so far, 1 name in all: 'appendLatin1To'. None can be made
  from Python: one comes out of a function of another class that gives one
  back.

  What has a ritual and is left out, and why
  ------------------------------------------

  - Qt's 'QAbstractConcatenable::~QAbstractConcatenable()': the destructor:
    Python removes its C++ QAbstractConcatenable by it, and has no other use
    for it.

  What has no ritual
  ------------------

  2 of the 4 functions Qt declares: 2 takes or gives a type that cannot be
  passed yet.

  What to expect
  --------------

  - The C++ QAbstractConcatenable is created at the first use, not by
    'QAbstractConcatenable(...)'.
  - A wrong argument is refused in Python, with 'DispatchException', and
    never reaches C++.
  - None is taken wherever Qt takes an object by its address, or text as C
    has it, and is passed on as nothing. Whether Qt can do with nothing there
    is as in C++.
  - A function giving a QAbstractConcatenable back gives a copy the ritual
    made for Python, in a new cute QAbstractConcatenable.
  """

