  @overload(QSize, QList[QRect], QRect)
  def place(self, size: QSize, rects: QList[QRect], domain: QRect) -> QPoint:
    """
    Calls Qt's 'QPoint QMdi::Placer::place(const QSize &size, const
    QList<QRect> &rects, const QRect &domain) const'.

    Qt's own words: https://doc.qt.io/qt-6/qmdi-placer.html#place

    Parameters
    ----------

    size : QSize
      Passed on as a value: Qt reads the C++ QSize, which stays Python's own.

    rects : QList[QRect]
      Passed on as a list of Qt: Qt reads the C++ list, which stays Python's
      own. A list or tuple of Python is made into one first, and refused when
      an element does not fit.

    domain : QRect
      Passed on as a value: Qt reads the C++ QRect, which stays Python's own.

    Returns
    -------

    QPoint
      A new cute QPoint around the copy Qt gave back. Python owns it.
    """
    #  QPoint QMdi::Placer::place(const QSize &size, const QList<QRect>
    #      &rects, const QRect &domain) const
    address = self.uglySide.call(
        'ritual_ZNK4QMdi6Placer5placeERK5QSizeRK5QListI5QRectERKS5_',
        self._valueOf(size), self._valueOf(rects), self._valueOf(domain),
    )
    from ..QtCore import QPoint
    return QPoint._cuteOwning(address)

