class Placer(CuteMixin, metaclass=MetaCute):
  """
  The cute side of Qt's QMdi::Placer: a plain Python object standing in front
  of one C++ QMdi::Placer.

  What exists
  -----------

  Every function of Qt's QMdi::Placer that has a ritual and that Python can
  call so far, 1 name in all: 'place'. None can be made from Python: one
  comes out of a function of another class that gives one back.

  What has a ritual and is left out, and why
  ------------------------------------------

  - Qt's 'QMdi::Placer::~Placer()': the destructor: Python never removes a
    C++ QMdi::Placer.

  What to expect
  --------------

  - The C++ QMdi::Placer is created at the first use, not by
    'QMdi::Placer(...)'.
  - A wrong argument is refused in Python, with 'DispatchException', and
    never reaches C++.
  - None is taken wherever Qt takes an object by its address, or text as C
    has it, and is passed on as nothing. Whether Qt can do with nothing there
    is as in C++.
  - Python never removes the C++ QMdi::Placer.
  """

