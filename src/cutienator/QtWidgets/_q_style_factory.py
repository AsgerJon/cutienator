    """
    Calls Qt's 'QStyle *QStyleFactory::create(const QString &a0)'.

    Qt's own words: https://doc.qt.io/qt-6/qstylefactory.html#create

    Parameters
    ----------

    a0 : str
      Passed on as it is: a QString is made of it for the call.

    Returns
    -------

    Optional[QStyle]
      The cute object standing for what Qt gave back. None when Qt gave back
      no object.
    """
    #  QStyle *QStyleFactory::create(const QString &a0)
    address = Rituals.call('ritual_ZN13QStyleFactory6createERK7QString', a0)
    from . import QStyle
    return QStyle._cuteAt(address)

