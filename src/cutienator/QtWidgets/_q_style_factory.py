class QStyleFactory(CuteMixin, metaclass=MetaCute):
  """
  The cute side of Qt's QStyleFactory: a plain Python object standing in
  front of one C++ QStyleFactory.

  C++ hands a QStyleFactory around as a copy, so every C++ QStyleFactory
  behind a cute one is Python's own: it is removed, by the ritual named in
  '__delete_ritual__', when the cute object goes.

  What exists
  -----------

  Every function of Qt's QStyleFactory that has a ritual and that Python can
  call so far, 1 name in all: 'create'. None can be made from Python: one
  comes out of a function of another class that gives one back.

  What has a ritual and is left out, and why
  ------------------------------------------

  - Qt's 'QStyleFactory::~QStyleFactory()': the destructor: Python removes
    its C++ QStyleFactory by it, and has no other use for it.

  What has no ritual
  ------------------

  1 of the 3 functions Qt declares: 1 takes or gives a type that cannot be
  passed yet.

  What to expect
  --------------

  - The C++ QStyleFactory is created at the first use, not by
    'QStyleFactory(...)'.
  - A wrong argument is refused in Python, with 'DispatchException', and
    never reaches C++.
  - None is taken wherever Qt takes an object by its address, or text as C
    has it, and is passed on as nothing. Whether Qt can do with nothing there
    is as in C++.
  - A function giving a QStyleFactory back gives a copy the ritual made for
    Python, in a new cute QStyleFactory.
  """

