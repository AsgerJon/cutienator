class QQuickItemsModule(CuteMixin, metaclass=MetaCute):
  """
  The cute side of Qt's QQuickItemsModule: a plain Python object standing in
  front of one C++ QQuickItemsModule.

  C++ hands a QQuickItemsModule around as a copy, so every C++
  QQuickItemsModule behind a cute one is Python's own: it is removed, by the
  ritual named in '__delete_ritual__', when the cute object goes.

  What exists
  -----------

  Every function of Qt's QQuickItemsModule that has a ritual and that Python
  can call so far, 1 name in all: 'defineModule'. None can be made from
  Python: one comes out of a function of another class that gives one back.

  What has a ritual and is left out, and why
  ------------------------------------------

  - Qt's 'QQuickItemsModule::~QQuickItemsModule()': the destructor: Python
    removes its C++ QQuickItemsModule by it, and has no other use for it.

  What to expect
  --------------

  - The C++ QQuickItemsModule is created at the first use, not by
    'QQuickItemsModule(...)'.
  - A wrong argument is refused in Python, with 'DispatchException', and
    never reaches C++.
  - None is taken wherever Qt takes an object by its address, or text as C
    has it, and is passed on as nothing. Whether Qt can do with nothing there
    is as in C++.
  - A function giving a QQuickItemsModule back gives a copy the ritual made
    for Python, in a new cute QQuickItemsModule.
  """

