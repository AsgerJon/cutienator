  @staticmethod
  @overload(QSGTexture)
  @overload(NoneType)
  def fromTexture(t: Optional[QSGTexture]) -> QSGSamplerDescription:
    """
    Calls Qt's 'QSGSamplerDescription
    QSGSamplerDescription::fromTexture(QSGTexture *t)'.

    Qt's own words:
    https://doc.qt.io/qt-6/qsgsamplerdescription.html#fromTexture

    Parameters
    ----------

    t : Optional[QSGTexture]
      Passed on as the address of its C++ object. None is passed on as no
      object.

    Returns
    -------

    QSGSamplerDescription
      A new cute QSGSamplerDescription around the copy Qt gave back. Python
      owns it.
    """
    #  QSGSamplerDescription QSGSamplerDescription::fromTexture(QSGTexture
    #      *t)
    address = Rituals.call(
        'ritual_ZN21QSGSamplerDescription11fromTextureEP10QSGTexture',
        CuteMixin._addressOf(t),
    )
    return QSGSamplerDescription._cuteOwning(address)

