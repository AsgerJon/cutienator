class QSvgG(QSvgStructureNode):
  """
  The cute side of Qt's QSvgG: a plain Python object standing in front of one
  C++ QSvgG.

  It is built on the cute 'QSvgStructureNode', as Qt's QSvgG is built on Qt's
  QSvgStructureNode, and has everything that class has.

  What exists
  -----------

  Every function of Qt's QSvgG that has a ritual and that Python can call so
  far, 2 names in all: 'type', 'requiresGroupRendering'. It can be made from
  Python, in 1 way; see '__init__'.

  What has a ritual and is left out, and why
  ------------------------------------------

  - Qt's 'QSvgG::~QSvgG()': the destructor: Python never removes a C++ QSvgG.
  - Qt's 'void QSvgG::drawCommand(QPainter *a0, QSvgExtraStates &a1)': takes
    a type Python has no way to hand over yet.
  - Qt's 'bool QSvgG::shouldDrawNode(QPainter *p, QSvgExtraStates &states)
    const': takes a type Python has no way to hand over yet.

  What to expect
  --------------

  - The C++ QSvgG is created at the first use, not by 'QSvgG(...)'.
  - A wrong argument is refused in Python, with 'DispatchException', and
    never reaches C++.
  - None is taken wherever Qt takes an object by its address, or text as C
    has it, and is passed on as nothing. Whether Qt can do with nothing there
    is as in C++.
  - Python never removes the C++ QSvgG.
  """

