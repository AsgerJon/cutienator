  def type(self) -> QSvgNode.Type:
    """
    Calls Qt's 'Type QSvgG::type() const'.

    Qt's own words: https://doc.qt.io/qt-6/qsvgg.html#type

    Returns
    -------

    QSvgNode.Type
      The member standing for the number Qt gave back. For a number Qt gives
      no name it is the member without a name that 'QSvgNode.Type(number)'
      gives.
    """
    #  Type QSvgG::type() const
    ritual = 'ritual_ZNK5QSvgG4typeEv'
    if self.uglySide.isOurs():
      ritual = 'ritual_own_ZNK5QSvgG4typeEv'
    return QSvgNode.Type(self.uglySide.call(ritual))

  def requiresGroupRendering(self) -> bool:
    """
    Calls Qt's 'bool QSvgG::requiresGroupRendering() const'.

    Qt's own words: https://doc.qt.io/qt-6/qsvgg.html#requiresGroupRendering
    """
    #  bool QSvgG::requiresGroupRendering() const
    ritual = 'ritual_ZNK5QSvgG22requiresGroupRenderingEv'
    if self.uglySide.isOurs():
      ritual = 'ritual_own_ZNK5QSvgG22requiresGroupRenderingEv'
    return self.uglySide.call(ritual)

