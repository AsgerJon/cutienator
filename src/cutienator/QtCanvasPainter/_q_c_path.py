class QCPath(CuteMixin, metaclass=MetaCute):
  """
  The cute side of Qt's QCPath: a plain Python object standing in front of
  one C++ QCPath.

  C++ hands a QCPath around as a copy, so every C++ QCPath behind a cute one
  is Python's own: it is removed, by the ritual named in '__delete_ritual__',
  when the cute object goes.

  What exists
  -----------

  No function of Qt's QCPath yet. None can be made from Python: one comes out
  of a function of another class that gives one back.

  What has a ritual and is left out, and why
  ------------------------------------------

  - Qt's 'QCPath::~QCPath()': the destructor: Python removes its C++ QCPath
    by it, and has no other use for it.

  What to expect
  --------------

  - The C++ QCPath is created at the first use, not by 'QCPath(...)'.
  - A wrong argument is refused in Python, with 'DispatchException', and
    never reaches C++.
  - None is taken wherever Qt takes an object by its address, or text as C
    has it, and is passed on as nothing. Whether Qt can do with nothing there
    is as in C++.
  - A function giving a QCPath back gives a copy the ritual made for Python,
    in a new cute QCPath.
  """

