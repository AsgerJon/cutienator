  """
  The cute side of Qt's QAbstractExtensionFactory: a plain Python object
  standing in front of one C++ QAbstractExtensionFactory.

  What exists
  -----------

  Every function of Qt's QAbstractExtensionFactory that has a ritual and that
  Python can call so far, 1 name in all: 'extension'. None can be made from
  Python: one comes out of a function of another class that gives one back.

  What has a ritual and is left out, and why
  ------------------------------------------

  - Qt's 'QAbstractExtensionFactory::~QAbstractExtensionFactory()': the
    destructor: Python never removes a C++ QAbstractExtensionFactory.

  What to expect
  --------------

  - The C++ QAbstractExtensionFactory is created at the first use, not by
    'QAbstractExtensionFactory(...)'.
  - A wrong argument is refused in Python, with 'DispatchException', and
    never reaches C++.
  - None is taken wherever Qt takes an object by its address, or text as C
    has it, and is passed on as nothing. Whether Qt can do with nothing there
    is as in C++.
  - Python never removes the C++ QAbstractExtensionFactory.
  """

