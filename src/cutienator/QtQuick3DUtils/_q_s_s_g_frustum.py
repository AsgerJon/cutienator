  @overload(QSSGBounds3)
  def contains(self, box: QSSGBounds3) -> bool:
    """
    Calls Qt's 'bool QSSGFrustum::contains(const QSSGBounds3 &box) const'.

    Qt's own words: https://doc.qt.io/qt-6/qssgfrustum.html#contains

    Parameters
    ----------

    box : QSSGBounds3
      Passed on as a value: Qt reads the C++ QSSGBounds3, which stays
      Python's own.
    """
    #  bool QSSGFrustum::contains(const QSSGBounds3 &box) const
    return self.uglySide.call(
        'ritual_ZNK11QSSGFrustum8containsERK11QSSGBounds3',
        self._valueOf(box),
    )

