class QQuick3D(CuteMixin, metaclass=MetaCute):
  """
  The cute side of Qt's QQuick3D: a plain Python object standing in front of
  one C++ QQuick3D.

  C++ hands a QQuick3D around as a copy, so every C++ QQuick3D behind a cute
  one is Python's own: it is removed, by the ritual named in
  '__delete_ritual__', when the cute object goes.

  What exists
  -----------

  Every function of Qt's QQuick3D that has a ritual and that Python can call
  so far, 1 name in all: 'idealSurfaceFormat'. None can be made from Python:
  one comes out of a function of another class that gives one back.

  What has a ritual and is left out, and why
  ------------------------------------------

  - Qt's 'QQuick3D::~QQuick3D()': the destructor: Python removes its C++
    QQuick3D by it, and has no other use for it.

  What to expect
  --------------

  - The C++ QQuick3D is created at the first use, not by 'QQuick3D(...)'.
  - A wrong argument is refused in Python, with 'DispatchException', and
    never reaches C++.
  - None is taken wherever Qt takes an object by its address, or text as C
    has it, and is passed on as nothing. Whether Qt can do with nothing there
    is as in C++.
  - A function giving a QQuick3D back gives a copy the ritual made for
    Python, in a new cute QQuick3D.
  """

  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
