  @staticmethod
  @overload()
  @overload(int)
  def idealSurfaceFormat(samples: int = -1) -> QSurfaceFormat:
    """
    Calls Qt's 'QSurfaceFormat QQuick3D::idealSurfaceFormat(int samples)'.

    Qt's own words: https://doc.qt.io/qt-6/qquick3d.html#idealSurfaceFormat

    Parameters
    ----------

    samples : int
      Passed on as it is. May be left out, as in Qt: it is then -1.

    Returns
    -------

    QSurfaceFormat
      A new cute QSurfaceFormat around the copy Qt gave back. Python owns it.
    """
    #  QSurfaceFormat QQuick3D::idealSurfaceFormat(int samples)
    address = Rituals.call(
        'ritual_ZN8QQuick3D18idealSurfaceFormatEi', samples,
    )
    from ..QtGui import QSurfaceFormat
    return QSurfaceFormat._cuteOwning(address)

