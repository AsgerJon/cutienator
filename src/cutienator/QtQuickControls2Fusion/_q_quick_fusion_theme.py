class QQuickFusionTheme(CuteMixin, metaclass=MetaCute):
  """
  The cute side of Qt's QQuickFusionTheme: a plain Python object standing in
  front of one C++ QQuickFusionTheme.

  C++ hands a QQuickFusionTheme around as a copy, so every C++
  QQuickFusionTheme behind a cute one is Python's own: it is removed, by the
  ritual named in '__delete_ritual__', when the cute object goes.

  What exists
  -----------

  Every function of Qt's QQuickFusionTheme that has a ritual and that Python
  can call so far, 1 name in all: 'initialize'. None can be made from Python:
  one comes out of a function of another class that gives one back.

  What has a ritual and is left out, and why
  ------------------------------------------

  - Qt's 'QQuickFusionTheme::~QQuickFusionTheme()': the destructor: Python
    removes its C++ QQuickFusionTheme by it, and has no other use for it.

  What to expect
  --------------

  - The C++ QQuickFusionTheme is created at the first use, not by
    'QQuickFusionTheme(...)'.
  - A wrong argument is refused in Python, with 'DispatchException', and
    never reaches C++.
  - None is taken wherever Qt takes an object by its address, or text as C
    has it, and is passed on as nothing. Whether Qt can do with nothing there
    is as in C++.
  - A function giving a QQuickFusionTheme back gives a copy the ritual made
    for Python, in a new cute QQuickFusionTheme.
  """

