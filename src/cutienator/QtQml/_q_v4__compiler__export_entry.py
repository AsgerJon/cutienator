class ExportEntry(CuteMixin, metaclass=MetaCute):
  """
  The cute side of Qt's QV4::Compiler::ExportEntry: a plain Python object
  standing in front of one C++ QV4::Compiler::ExportEntry.

  C++ hands a QV4::Compiler::ExportEntry around as a copy, so every C++
  QV4::Compiler::ExportEntry behind a cute one is Python's own: it is
  removed, by the ritual named in '__delete_ritual__', when the cute object
  goes.

  What exists
  -----------

  Every function of Qt's QV4::Compiler::ExportEntry that has a ritual and
  that Python can call so far, 1 name in all: 'lessThan'. None can be made
  from Python: one comes out of a function of another class that gives one
  back.

  What has a ritual and is left out, and why
  ------------------------------------------

  - Qt's 'QV4::Compiler::ExportEntry::~ExportEntry()': the destructor: Python
    removes its C++ QV4::Compiler::ExportEntry by it, and has no other use
    for it.

  What to expect
  --------------

  - The C++ QV4::Compiler::ExportEntry is created at the first use, not by
    'QV4::Compiler::ExportEntry(...)'.
  - A wrong argument is refused in Python, with 'DispatchException', and
    never reaches C++.
  - None is taken wherever Qt takes an object by its address, or text as C
    has it, and is passed on as nothing. Whether Qt can do with nothing there
    is as in C++.
  - A function giving a QV4::Compiler::ExportEntry back gives a copy the
    ritual made for Python, in a new cute QV4::Compiler::ExportEntry.
  """

