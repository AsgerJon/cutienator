class RegisterType(CuteMixin, metaclass=MetaCute):
  """
  The cute side of Qt's QQmlPrivate::RegisterType: a plain Python object
  standing in front of one C++ QQmlPrivate::RegisterType.

  C++ hands a QQmlPrivate::RegisterType around as a copy, so every C++
  QQmlPrivate::RegisterType behind a cute one is Python's own: it is removed,
  by the ritual named in '__delete_ritual__', when the cute object goes.

  What exists
  -----------

  Every function of Qt's QQmlPrivate::RegisterType that has a ritual and that
  Python can call so far, 1 name in all: 'has'. None can be made from Python:
  one comes out of a function of another class that gives one back.

  What has a ritual and is left out, and why
  ------------------------------------------

  - Qt's 'QQmlPrivate::RegisterType::~RegisterType()': the destructor: Python
    removes its C++ QQmlPrivate::RegisterType by it, and has no other use for
    it.

  What to expect
  --------------

  - The C++ QQmlPrivate::RegisterType is created at the first use, not by
    'QQmlPrivate::RegisterType(...)'.
  - A wrong argument is refused in Python, with 'DispatchException', and
    never reaches C++.
  - None is taken wherever Qt takes an object by its address, or text as C
    has it, and is passed on as nothing. Whether Qt can do with nothing there
    is as in C++.
  - A function giving a QQmlPrivate::RegisterType back gives a copy the
    ritual made for Python, in a new cute QQmlPrivate::RegisterType.
  """

