class QQmlDebugServer(QQmlDebugConnector):
  """
  The cute side of Qt's QQmlDebugServer: a plain Python object standing in
  front of one C++ QQmlDebugServer.

  It is built on the cute 'QQmlDebugConnector', as Qt's QQmlDebugServer is
  built on Qt's QQmlDebugConnector, and has everything that class has.

  What exists
  -----------

  Every function of Qt's QQmlDebugServer that has a ritual and that Python
  can call so far, 3 names in all: 'metaObject', 'tr', 'setDevice'. None can
  be made from Python: one comes out of a function of another class that
  gives one back.

  What has a ritual and is left out, and why
  ------------------------------------------

  - Qt's 'void *QQmlDebugServer::qt_metacast(const char *a0)': one of Qt's
    own inner workings.
  - Qt's 'int QQmlDebugServer::qt_metacall(QMetaObject::Call a0, int a1, void
    **a2)': one of Qt's own inner workings.
  - Qt's 'QQmlDebugServer::~QQmlDebugServer()': the destructor: Python never
    removes a C++ QQmlDebugServer.

  What has no ritual
  ------------------

  2 of the 8 functions Qt declares: 2 not a gap.

  What to expect
  --------------

  - The C++ QQmlDebugServer is created at the first use, not by
    'QQmlDebugServer(...)'.
  - A wrong argument is refused in Python, with 'DispatchException', and
    never reaches C++.
  - None is taken wherever Qt takes an object by its address, or text as C
    has it, and is passed on as nothing. Whether Qt can do with nothing there
    is as in C++.
  - Python never removes the C++ QQmlDebugServer.
  - Qt tells when it has removed the C++ QQmlDebugServer. Every call on the
    cute object, and every use of it as an argument, then raises
    'RuntimeError', and nothing reaches C++.
  """

