class QBitRef(CuteMixin, metaclass=MetaCute):
  """
  The cute side of Qt's QBitRef: a plain Python object standing in front of
  one C++ QBitRef.

  C++ hands a QBitRef around as a copy, so every C++ QBitRef behind a cute
  one is Python's own: it is removed, by the ritual named in
  '__delete_ritual__', when the cute object goes.

  What exists
  -----------

  Every function of Qt's QBitRef that has a ritual and that Python can call
  so far, 1 name in all: '__bool__'. None can be made from Python: one comes
  out of a function of another class that gives one back.

  What has a ritual and is left out, and why
  ------------------------------------------

  - Qt's 'QBitRef::QBitRef(QBitArray &array, qsizetype idx)': takes a type
    Python has no way to hand over yet.
  - Qt's 'bool QBitRef::operator!() const': an operator Python has no name
    for.
  - Qt's 'QBitRef &QBitRef::operator=(const QBitRef &val)': assignment:
    Python binds a name and has no operator for it.
  - Qt's 'QBitRef &QBitRef::operator=(bool val)': assignment: Python binds a
    name and has no operator for it.
  - Qt's 'QBitRef::~QBitRef()': the destructor: Python removes its C++
    QBitRef by it, and has no other use for it.

  What to expect
  --------------

  - The C++ QBitRef is created at the first use, not by 'QBitRef(...)'.
  - A wrong argument is refused in Python, with 'DispatchException', and
    never reaches C++.
  - None is taken wherever Qt takes an object by its address, or text as C
    has it, and is passed on as nothing. Whether Qt can do with nothing there
    is as in C++.
  - A function giving a QBitRef back gives a copy the ritual made for Python,
    in a new cute QBitRef.
  - Each name of Qt's QBitRef that has no cute function yet, '__init__',
    holds a function that raises 'NotImplementedError', and its docstring
    says why.
  """

