class QBindingStatus(CuteMixin, metaclass=MetaCute):
  """
  The cute side of Qt's QBindingStatus: a plain Python object standing in
  front of one C++ QBindingStatus.

  C++ hands a QBindingStatus around as a copy, so every C++ QBindingStatus
  behind a cute one is Python's own: it is removed, by the ritual named in
  '__delete_ritual__', when the cute object goes.

  What exists
  -----------

  No function of Qt's QBindingStatus yet. None can be made from Python: one
  comes out of a function of another class that gives one back.

  What has a ritual and is left out, and why
  ------------------------------------------

  - Qt's 'QBindingStatus::~QBindingStatus()': the destructor: Python removes
    its C++ QBindingStatus by it, and has no other use for it.

  What to expect
  --------------

  - The C++ QBindingStatus is created at the first use, not by
    'QBindingStatus(...)'.
  - A wrong argument is refused in Python, with 'DispatchException', and
    never reaches C++.
  - None is taken wherever Qt takes an object by its address, or text as C
    has it, and is passed on as nothing. Whether Qt can do with nothing there
    is as in C++.
  - A function giving a QBindingStatus back gives a copy the ritual made for
    Python, in a new cute QBindingStatus.
  """

