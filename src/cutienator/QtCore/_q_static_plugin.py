class QStaticPlugin(CuteMixin, metaclass=MetaCute):
  """
  The cute side of Qt's QStaticPlugin: a plain Python object standing in
  front of one C++ QStaticPlugin.

  C++ hands a QStaticPlugin around as a copy, so every C++ QStaticPlugin
  behind a cute one is Python's own: it is removed, by the ritual named in
  '__delete_ritual__', when the cute object goes.

  What exists
  -----------

  Every function of Qt's QStaticPlugin that has a ritual and that Python can
  call so far, 1 name in all: 'metaData'. None can be made from Python: one
  comes out of a function of another class that gives one back.

  What has a ritual and is left out, and why
  ------------------------------------------

  - Qt's 'QStaticPlugin::~QStaticPlugin()': the destructor: Python removes
    its C++ QStaticPlugin by it, and has no other use for it.

  What has no ritual
  ------------------

  1 of the 3 functions Qt declares: 1 takes or gives a type that cannot be
  passed yet.

  What to expect
  --------------

  - The C++ QStaticPlugin is created at the first use, not by
    'QStaticPlugin(...)'.
  - A wrong argument is refused in Python, with 'DispatchException', and
    never reaches C++.
  - None is taken wherever Qt takes an object by its address, or text as C
    has it, and is passed on as nothing. Whether Qt can do with nothing there
    is as in C++.
  - A function giving a QStaticPlugin back gives a copy the ritual made for
    Python, in a new cute QStaticPlugin.
  """

