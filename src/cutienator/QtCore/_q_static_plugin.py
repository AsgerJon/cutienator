    """
    Calls Qt's 'QJsonObject QStaticPlugin::metaData() const'.

    Qt's own words: https://doc.qt.io/qt-6/qstaticplugin.html#metaData

    Returns
    -------

    QJsonObject
      A new cute QJsonObject around the copy Qt gave back. Python owns it.
    """
    #  QJsonObject QStaticPlugin::metaData() const
    address = self.uglySide.call('ritual_ZNK13QStaticPlugin8metaDataEv')
    from . import QJsonObject
    return QJsonObject._cuteOwning(address)

