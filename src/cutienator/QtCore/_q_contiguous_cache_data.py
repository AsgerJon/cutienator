NoneType = type(None)


class QContiguousCacheData(CuteMixin, metaclass=MetaCute):
  """
  The cute side of Qt's QContiguousCacheData: a plain Python object standing
  in front of one C++ QContiguousCacheData.

  What exists
  -----------

  Every function of Qt's QContiguousCacheData that has a ritual and that
  Python can call so far, 2 names in all: 'allocateData', 'freeData'. None
  can be made from Python: one comes out of a function of another class that
  gives one back.

  What to expect
  --------------

  - The C++ QContiguousCacheData is created at the first use, not by
    'QContiguousCacheData(...)'.
  - A wrong argument is refused in Python, with 'DispatchException', and
    never reaches C++.
  - None is taken wherever Qt takes an object by its address, or text as C
    has it, and is passed on as nothing. Whether Qt can do with nothing there
    is as in C++.
  - Python never removes the C++ QContiguousCacheData.
  """

