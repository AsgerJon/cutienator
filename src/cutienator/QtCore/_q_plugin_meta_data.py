class QPluginMetaData(CuteMixin, metaclass=MetaCute):
  """
  The cute side of Qt's QPluginMetaData: a plain Python object standing in
  front of one C++ QPluginMetaData.

  C++ hands a QPluginMetaData around as a copy, so every C++ QPluginMetaData
  behind a cute one is Python's own: it is removed, by the ritual named in
  '__delete_ritual__', when the cute object goes.

  What exists
  -----------

  Every function of Qt's QPluginMetaData that has a ritual and that Python
  can call so far, 1 name in all: 'archRequirements'. None can be made from
  Python: one comes out of a function of another class that gives one back.

  What has a ritual and is left out, and why
  ------------------------------------------

  - Qt's 'QPluginMetaData::~QPluginMetaData()': the destructor: Python
    removes its C++ QPluginMetaData by it, and has no other use for it.

  What has no ritual
  ------------------

  1 of the 3 functions Qt declares: 1 a template.

  What to expect
  --------------

  - The C++ QPluginMetaData is created at the first use, not by
    'QPluginMetaData(...)'.
  - A wrong argument is refused in Python, with 'DispatchException', and
    never reaches C++.
  - None is taken wherever Qt takes an object by its address, or text as C
    has it, and is passed on as nothing. Whether Qt can do with nothing there
    is as in C++.
  - A function giving a QPluginMetaData back gives a copy the ritual made for
    Python, in a new cute QPluginMetaData.
  """

