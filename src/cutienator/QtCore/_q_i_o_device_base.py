  """
  The cute side of Qt's QIODeviceBase: a plain Python object standing in
  front of one C++ QIODeviceBase.

  What exists
  -----------

  No function of Qt's QIODeviceBase yet. None can be made from Python: one
  comes out of a function of another class that gives one back.

  What has a ritual and is left out, and why
  ------------------------------------------

  - Qt's 'QIODeviceBase::~QIODeviceBase()': the destructor: Python never
    removes a C++ QIODeviceBase.

  What to expect
  --------------

  - The C++ QIODeviceBase is created at the first use, not by
    'QIODeviceBase(...)'.
  - A wrong argument is refused in Python, with 'DispatchException', and
    never reaches C++.
  - None is taken wherever Qt takes an object by its address, or text as C
    has it, and is passed on as nothing. Whether Qt can do with nothing there
    is as in C++.
  - Python never removes the C++ QIODeviceBase.
  """

