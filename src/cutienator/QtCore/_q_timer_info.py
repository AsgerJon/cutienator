class QTimerInfo(CuteMixin, metaclass=MetaCute):
  """
  The cute side of Qt's QTimerInfo: a plain Python object standing in front
  of one C++ QTimerInfo.

  C++ hands a QTimerInfo around as a copy, so every C++ QTimerInfo behind a
  cute one is Python's own: it is removed, by the ritual named in
  '__delete_ritual__', when the cute object goes.

  What exists
  -----------

  No function of Qt's QTimerInfo yet. None can be made from Python: one comes
  out of a function of another class that gives one back.

  What has a ritual and is left out, and why
  ------------------------------------------

  - Qt's 'QTimerInfo::QTimerInfo(Qt::TimerId timerId, Duration interval,
    Qt::TimerType type, QObject *obj)': takes a type Python has no way to
    hand over yet.
  - Qt's 'QTimerInfo::~QTimerInfo()': the destructor: Python removes its C++
    QTimerInfo by it, and has no other use for it.

  What to expect
  --------------

  - The C++ QTimerInfo is created at the first use, not by 'QTimerInfo(...)'.
  - A wrong argument is refused in Python, with 'DispatchException', and
    never reaches C++.
  - None is taken wherever Qt takes an object by its address, or text as C
    has it, and is passed on as nothing. Whether Qt can do with nothing there
    is as in C++.
  - A function giving a QTimerInfo back gives a copy the ritual made for
    Python, in a new cute QTimerInfo.
  - Each name of Qt's QTimerInfo that has no cute function yet, '__init__',
    holds a function that raises 'NotImplementedError', and its docstring
    says why.
  """

