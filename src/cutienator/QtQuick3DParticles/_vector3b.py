class Vector3b(CuteMixin, metaclass=MetaCute):
  """
  The cute side of Qt's Vector3b: a plain Python object standing in front of
  one C++ Vector3b.

  C++ hands a Vector3b around as a copy, so every C++ Vector3b behind a cute
  one is Python's own: it is removed, by the ritual named in
  '__delete_ritual__', when the cute object goes.

  What exists
  -----------

  No function of Qt's Vector3b yet. None can be made from Python: one comes
  out of a function of another class that gives one back.

  What has a ritual and is left out, and why
  ------------------------------------------

  - Qt's 'Vector3b::~Vector3b()': the destructor: Python removes its C++
    Vector3b by it, and has no other use for it.

  What to expect
  --------------

  - The C++ Vector3b is created at the first use, not by 'Vector3b(...)'.
  - A wrong argument is refused in Python, with 'DispatchException', and
    never reaches C++.
  - None is taken wherever Qt takes an object by its address, or text as C
    has it, and is passed on as nothing. Whether Qt can do with nothing there
    is as in C++.
  - A function giving a Vector3b back gives a copy the ritual made for
    Python, in a new cute Vector3b.
  """

