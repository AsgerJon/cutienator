class Value(CuteMixin, metaclass=MetaCute):
  """
  The cute side of Qt's QCss::Value: a plain Python object standing in front
  of one C++ QCss::Value.

  C++ hands a QCss::Value around as a copy, so every C++ QCss::Value behind a
  cute one is Python's own: it is removed, by the ritual named in
  '__delete_ritual__', when the cute object goes.

  What exists
  -----------

  Every function of Qt's QCss::Value that has a ritual and that Python can
  call so far, 1 name in all: 'toString'. It can be made from Python, in 1
  way; see '__init__'.

  What has a ritual and is left out, and why
  ------------------------------------------

  - Qt's 'QCss::Value::~Value()': the destructor: Python removes its C++
    QCss::Value by it, and has no other use for it.

  What to expect
  --------------

  - The C++ QCss::Value is created at the first use, not by
    'QCss::Value(...)'.
  - A wrong argument is refused in Python, with 'DispatchException', and
    never reaches C++.
  - None is taken wherever Qt takes an object by its address, or text as C
    has it, and is passed on as nothing. Whether Qt can do with nothing there
    is as in C++.
  - A function giving a QCss::Value back gives a copy the ritual made for
    Python, in a new cute QCss::Value.
  """

