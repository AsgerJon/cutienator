    """
    Calls Qt's 'QRhiDriverInfo QRhiAdapter::info() const'.

    Qt's own words: https://doc.qt.io/qt-6/qrhiadapter.html#info

    Returns
    -------

    QRhiDriverInfo
      A new cute QRhiDriverInfo around the copy Qt gave back. Python owns it.
    """
