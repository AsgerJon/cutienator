  """
  The cute side of Qt's QValidator: a plain Python object standing in front
  of one C++ QValidator.

  It is built on the cute 'QObject', as Qt's QValidator is built on Qt's
  QObject, and has everything that class has.

  What exists
  -----------

  Every function of Qt's QValidator that has a ritual and that Python can
  call so far, 4 names in all: 'metaObject', 'tr', 'setLocale', 'locale'.
  None can be made from Python: one comes out of a function of another class
  that gives one back.

  What has a ritual and is left out, and why
  ------------------------------------------

  - Qt's 'QValidator::~QValidator()': the destructor: Python never removes a
    C++ QValidator.

  What has no ritual
  ------------------

  14 of the 19 functions Qt declares: 4 takes or gives a type that cannot be
  passed yet; 3 private; 2 protected; 2 forbidden; 1 a template; 1 the class
  is abstract, so C++ cannot make one; 1 a signal.

  What to expect
  --------------

  - The C++ QValidator is created at the first use, not by 'QValidator(...)'.
  - A wrong argument is refused in Python, with 'DispatchException', and
    never reaches C++.
  - None is taken wherever Qt takes an object by its address, or text as C
    has it, and is passed on as nothing. Whether Qt can do with nothing there
    is as in C++.
  - Python never removes the C++ QValidator.
  - Qt tells when it has removed the C++ QValidator. Every call on the cute
    object, and every use of it as an argument, then raises 'RuntimeError',
    and nothing reaches C++.
  """

