class QVulkanAdapter(QRhiAdapter):
  """
  The cute side of Qt's QVulkanAdapter: a plain Python object standing in
  front of one C++ QVulkanAdapter.

  It is built on the cute 'QRhiAdapter', as Qt's QVulkanAdapter is built on
  Qt's QRhiAdapter, and has everything that class has.

  C++ hands a QVulkanAdapter around as a copy, so every C++ QVulkanAdapter
  behind a cute one is Python's own: it is removed, by the ritual named in
  '__delete_ritual__', when the cute object goes.

  What exists
  -----------

  Every function of Qt's QVulkanAdapter that has a ritual and that Python can
  call so far, 1 name in all: 'info'. None can be made from Python: one comes
  out of a function of another class that gives one back.

  What has a ritual and is left out, and why
  ------------------------------------------

  - Qt's 'QVulkanAdapter::~QVulkanAdapter()': the destructor: Python removes
    its C++ QVulkanAdapter by it, and has no other use for it.

  What to expect
  --------------

  - The C++ QVulkanAdapter is created at the first use, not by
    'QVulkanAdapter(...)'.
  - A wrong argument is refused in Python, with 'DispatchException', and
    never reaches C++.
  - None is taken wherever Qt takes an object by its address, or text as C
    has it, and is passed on as nothing. Whether Qt can do with nothing there
    is as in C++.
  - A function giving a QVulkanAdapter back gives a copy the ritual made for
    Python, in a new cute QVulkanAdapter.
  """

