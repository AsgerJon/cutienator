  def info(self) -> QRhiDriverInfo:
    """
    Calls Qt's 'QRhiDriverInfo QVulkanAdapter::info() const'.

    Qt's own words: https://doc.qt.io/qt-6/qvulkanadapter.html#info

    Returns
    -------

    QRhiDriverInfo
      A new cute QRhiDriverInfo around the copy Qt gave back. Python owns it.
    """
    #  QRhiDriverInfo QVulkanAdapter::info() const
    ritual = 'ritual_ZNK14QVulkanAdapter4infoEv'
    if self.uglySide.isOurs():
      ritual = 'ritual_own_ZNK14QVulkanAdapter4infoEv'
    address = self.uglySide.call(ritual)
    from . import QRhiDriverInfo
    return QRhiDriverInfo._cuteOwning(address)

