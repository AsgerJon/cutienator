class QGenericPluginFactory(CuteMixin, metaclass=MetaCute):
  """
  The cute side of Qt's QGenericPluginFactory: a plain Python object standing
  in front of one C++ QGenericPluginFactory.

  C++ hands a QGenericPluginFactory around as a copy, so every C++
  QGenericPluginFactory behind a cute one is Python's own: it is removed, by
  the ritual named in '__delete_ritual__', when the cute object goes.

  What exists
  -----------

  Every function of Qt's QGenericPluginFactory that has a ritual and that
  Python can call so far, 2 names in all: 'keys', 'create'. None can be made
  from Python: one comes out of a function of another class that gives one
  back.

  What has a ritual and is left out, and why
  ------------------------------------------

  - Qt's 'QGenericPluginFactory::~QGenericPluginFactory()': the destructor:
    Python removes its C++ QGenericPluginFactory by it, and has no other use
    for it.

  What to expect
  --------------

  - The C++ QGenericPluginFactory is created at the first use, not by
    'QGenericPluginFactory(...)'.
  - A wrong argument is refused in Python, with 'DispatchException', and
    never reaches C++.
  - None is taken wherever Qt takes an object by its address, or text as C
    has it, and is passed on as nothing. Whether Qt can do with nothing there
    is as in C++.
  - A function giving a QGenericPluginFactory back gives a copy the ritual
    made for Python, in a new cute QGenericPluginFactory.
  """

