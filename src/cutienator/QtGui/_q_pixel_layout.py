class QPixelLayout(CuteMixin, metaclass=MetaCute):
  """
  The cute side of Qt's QPixelLayout: a plain Python object standing in front
  of one C++ QPixelLayout.

  C++ hands a QPixelLayout around as a copy, so every C++ QPixelLayout behind
  a cute one is Python's own: it is removed, by the ritual named in
  '__delete_ritual__', when the cute object goes.

  What exists
  -----------

  No function of Qt's QPixelLayout yet. None can be made from Python: one
  comes out of a function of another class that gives one back.

  What has a ritual and is left out, and why
  ------------------------------------------

  - Qt's 'QPixelLayout::~QPixelLayout()': the destructor: Python removes its
    C++ QPixelLayout by it, and has no other use for it.

  What to expect
  --------------

  - The C++ QPixelLayout is created at the first use, not by
    'QPixelLayout(...)'.
  - A wrong argument is refused in Python, with 'DispatchException', and
    never reaches C++.
  - None is taken wherever Qt takes an object by its address, or text as C
    has it, and is passed on as nothing. Whether Qt can do with nothing there
    is as in C++.
  - A function giving a QPixelLayout back gives a copy the ritual made for
    Python, in a new cute QPixelLayout.
  """

