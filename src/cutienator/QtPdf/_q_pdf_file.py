class QPdfFile(QFile):
  """
  The cute side of Qt's QPdfFile: a plain Python object standing in front of
  one C++ QPdfFile.

  It is built on the cute 'QFile', as Qt's QPdfFile is built on Qt's QFile,
  and has everything that class has.

  What exists
  -----------

  Every function of Qt's QPdfFile that has a ritual and that Python can call
  so far, 3 names in all: 'metaObject', 'tr', 'document'. It can be made from
  Python, in 1 way; see '__init__'.

  What has a ritual and is left out, and why
  ------------------------------------------

  - Qt's 'void *QPdfFile::qt_metacast(const char *a0)': one of Qt's own inner
    workings.
  - Qt's 'int QPdfFile::qt_metacall(QMetaObject::Call a0, int a1, void
    **a2)': one of Qt's own inner workings.

  What has no ritual
  ------------------

  2 of the 8 functions Qt declares: 2 not a gap.

  What to expect
  --------------

  - The C++ QPdfFile is created at the first use, not by 'QPdfFile(...)'.
  - A wrong argument is refused in Python, with 'DispatchException', and
    never reaches C++.
  - None is taken wherever Qt takes an object by its address, or text as C
    has it, and is passed on as nothing. Whether Qt can do with nothing there
    is as in C++.
  - Python never removes the C++ QPdfFile.
  - Qt tells when it has removed the C++ QPdfFile. Every call on the cute
    object, and every use of it as an argument, then raises 'RuntimeError',
    and nothing reaches C++.
  """

