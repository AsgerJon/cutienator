class Color4ub(CuteMixin, metaclass=MetaCute):
  """
  The cute side of Qt's Color4ub: a plain Python object standing in front of
  one C++ Color4ub.

  C++ hands a Color4ub around as a copy, so every C++ Color4ub behind a cute
  one is Python's own: it is removed, by the ritual named in
  '__delete_ritual__', when the cute object goes.

  What exists
  -----------

  No function of Qt's Color4ub yet. None can be made from Python: one comes
  out of a function of another class that gives one back.

  What has a ritual and is left out, and why
  ------------------------------------------

  - Qt's 'Color4ub::~Color4ub()': the destructor: Python removes its C++
    Color4ub by it, and has no other use for it.

  What to expect
  --------------

  - The C++ Color4ub is created at the first use, not by 'Color4ub(...)'.
  - A wrong argument is refused in Python, with 'DispatchException', and
    never reaches C++.
  - None is taken wherever Qt takes an object by its address, or text as C
    has it, and is passed on as nothing. Whether Qt can do with nothing there
    is as in C++.
  - A function giving a Color4ub back gives a copy the ritual made for
    Python, in a new cute Color4ub.
  """

