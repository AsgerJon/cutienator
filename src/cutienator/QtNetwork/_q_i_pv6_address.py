class QIPv6Address(CuteMixin, metaclass=MetaCute):
  """
  The cute side of Qt's QIPv6Address: a plain Python object standing in front
  of one C++ QIPv6Address.

  C++ hands a QIPv6Address around as a copy, so every C++ QIPv6Address behind
  a cute one is Python's own: it is removed, by the ritual named in
  '__delete_ritual__', when the cute object goes.

  What exists
  -----------

  Every function of Qt's QIPv6Address that has a ritual and that Python can
  call so far, 1 name in all: '__getitem__'. None can be made from Python:
  one comes out of a function of another class that gives one back.

  What has a ritual and is left out, and why
  ------------------------------------------

  - Qt's 'QIPv6Address::~QIPv6Address()': the destructor: Python removes its
    C++ QIPv6Address by it, and has no other use for it.

  What has no ritual
  ------------------

  1 of the 3 functions Qt declares: 1 takes or gives a type that cannot be
  passed yet.

  What to expect
  --------------

  - The C++ QIPv6Address is created at the first use, not by
    'QIPv6Address(...)'.
  - A wrong argument is refused in Python, with 'DispatchException', and
    never reaches C++.
  - None is taken wherever Qt takes an object by its address, or text as C
    has it, and is passed on as nothing. Whether Qt can do with nothing there
    is as in C++.
  - A function giving a QIPv6Address back gives a copy the ritual made for
    Python, in a new cute QIPv6Address.
  """

